Future<void> ensureKazakhstanOcedSeeded() async {
  final firestore = FirebaseFirestore.instance;
  final kzSnapshot = await firestore
      .collection('oced')
      .where('country', isEqualTo: 'Казахстан')
      .limit(1)
      .get();
  if (kzSnapshot.docs.isNotEmpty) return;

  final batch = firestore.batch();
  for (final item in _kzOcedSeed) {
    final code = (item['kod'] ?? '').trim();
    if (code.isEmpty) continue;
    final ref = firestore.collection('oced').doc('kz_$code');
    batch.set(
        ref,
        {
          'kod': code,
          'title': item['title'],
          'country': 'Казахстан',
          'section': code.substring(0, 1),
          'updatedAt': FieldValue.serverTimestamp(),
          'createdAt': FieldValue.serverTimestamp(),
        },
        SetOptions(merge: true));
  }
  await batch.commit();
}
